"""Translate float64.glsl into an MSL library for nir_to_msl.

Metal has no double type. nir_to_msl prints fp64 ALU as calls into this
library, which works on the bits as 64-bit integers, instead of inlining the
library at every use like nir_lower_doubles does. Inlining made shaders with
many double operations too large for the Metal compiler.

The translation is mechanical: GLSL out parameters become references, mix()
gets typed helpers and the few GLSL built-ins the library uses get MSL
equivalents. Functions are static so the Metal compiler drops the unused ones
and chooses what to inline.
"""

import argparse
import re

PRELUDE = r"""
typedef ulong uint64_t;
typedef long int64_t;
typedef uint2 uvec2;
typedef int2 ivec2;
typedef bool2 bvec2;

#define KK_INLINE static inline __attribute__((always_inline))
KK_INLINE uint kk_mix(uint a, uint b, bool c) { return c ? b : a; }
KK_INLINE int kk_mix(int a, int b, bool c) { return c ? b : a; }
KK_INLINE ulong kk_mix(ulong a, ulong b, bool c) { return c ? b : a; }
KK_INLINE long kk_mix(long a, long b, bool c) { return c ? b : a; }
KK_INLINE float kk_mix(float a, float b, bool c) { return c ? b : a; }
KK_INLINE uint2 kk_mix(uint2 a, uint2 b, bool2 c) { return select(a, b, c); }
KK_INLINE uint2 unpackUint2x32(ulong x) { return uint2(uint(x), uint(x >> 32)); }
KK_INLINE int2 unpackInt2x32(long x) { return int2(int(x), int(x >> 32)); }
KK_INLINE ulong packUint2x32(uint2 v) { return ulong(v.x) | (ulong(v.y) << 32); }
KK_INLINE void umulExtended(uint a, uint b, thread uint &msb, thread uint &lsb)
{
   ulong p = ulong(a) * ulong(b);
   msb = uint(p >> 32);
   lsb = uint(p);
}
KK_INLINE float uintBitsToFloat(uint x) { return as_type<float>(x); }
KK_INLINE uint floatBitsToUint(float x) { return as_type<uint>(x); }
KK_INLINE int findMSB(uint a) { return a == 0u ? -1 : 31 - int(clz(a)); }
"""

RETURN_TYPES = r"(uint64_t|int64_t|bool|uint|int|void|float)"


# Literal fixes for spots the generic rules get wrong, with how often each
# must apply. Fail the build if float64.glsl changes under them.
FIXES = [
    # Both literals are ints in GLSL, but 0x80000000 is unsigned in MSL
    ("kk_mix(0x7FFFFFFF, 0x80000000,",
     "kk_mix(int(0x7FFFFFFF), int(0x80000000),", 2),
    # MSL cannot bind a reference to a vector component, so pass the out
    # parameters through temporaries.
    ("__shortShift64Left(a.y, a.x, 12, a.y, a.x);",
     "{ uint t0, t1; __shortShift64Left(a.y, a.x, 12, t0, t1); "
     "a.y = t0; a.x = t1; }", 1),
]


def translate(glsl):
    counts = [0] * len(FIXES)
    out = []
    for line in glsl.splitlines():
        if re.match(r"^#(version|extension|pragma)", line):
            continue
        line = re.sub(r"\bout (uint|int) ", r"thread \1 &", line)
        line = re.sub(r"\bmix\(", "kk_mix(", line)
        for i, (old, new, _) in enumerate(FIXES):
            counts[i] += line.count(old)
            line = line.replace(old, new)
        # Return types sit alone on the line before each function name
        line = re.sub(r"^" + RETURN_TYPES + r"$", r"static \1", line)
        out.append(line)
    for (old, _, expected), count in zip(FIXES, counts):
        if count != expected:
            raise SystemExit(f"float64.glsl changed: found '{old}' {count} "
                             f"times instead of {expected}")
    return PRELUDE + "\n".join(out) + "\n"


def c_string(text):
    lines = []
    for line in text.splitlines():
        line = line.replace("\\", "\\\\").replace('"', '\\"')
        lines.append('   "' + line + '\\n"')
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("glsl")
    parser.add_argument("header")
    args = parser.parse_args()

    with open(args.glsl, encoding="utf-8") as f:
        msl = translate(f.read())

    with open(args.header, "w", encoding="utf-8") as f:
        f.write("/* Generated by msl_float64_gen.py from float64.glsl */\n")
        f.write("static const char msl_float64_library[] =\n")
        f.write(c_string(msl))
        f.write(";\n")


if __name__ == "__main__":
    main()
